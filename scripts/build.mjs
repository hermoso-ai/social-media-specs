// Writes src/data.js from data/*.json, so the package imports the data as plain JS in Node and in every bundler.
// `node scripts/build.mjs --check` fails when src/data.js is out of date (CI runs it).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => JSON.parse(readFileSync(path.join(root, 'data', f), 'utf8'));
const parts = {
  textLimits: read('text-limits.json'),
  adCopy: read('ad-copy.json'),
  placements: read('placements.json'),
  safeZones: read('safe-zones.json'),
};
const out = '// Generated by scripts/build.mjs from data/*.json. Edit the JSON, then run `npm run build`.\n' +
  Object.entries(parts).map(([k, v]) => `export const ${k} = ${JSON.stringify(v, null, 2)};\n`).join('\n');
const target = path.join(root, 'src', 'data.js');

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(target, 'utf8'); } catch {}
  if (current !== out) { console.error('src/data.js is out of date: run `npm run build`.'); process.exit(1); }
  console.log('src/data.js is up to date.');
} else {
  writeFileSync(target, out);
  console.log('wrote src/data.js');
}
